<?php

declare(strict_types=1);

if (PHP_SAPI !== "cli") {
    http_response_code(403);
    exit("Migrations must run from the command line.");
}

require_once __DIR__ . "/maintenance/Mode.php";
try {
    $maintenanceLocks = MaintenanceMode::commandLock(false);
} catch (Throwable $e) {
    fwrite(STDERR, $e->getMessage() . PHP_EOL);
    exit(1);
}
register_shutdown_function(static function () use ($maintenanceLocks) {
    MaintenanceMode::release($maintenanceLocks);
});

$db = require __DIR__ . "/db.php";

$db->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

$driver = $db->getAttribute(PDO::ATTR_DRIVER_NAME);
$command = $argv[1] ?? "migrate";

if (!in_array($driver, ["mysql", "pgsql", "sqlite"], true)) {
    exit("Unsupported database driver: {$driver}\n");
}

if (!in_array($command, ["migrate", "rollback", "status"], true)) {
    exit("Usage: php php/migrate.php [migrate|rollback|status]\n");
}

/*
|--------------------------------------------------------------------------
| Migration tracking table
|--------------------------------------------------------------------------
*/

$primaryKey = match ($driver) {
    "mysql" => "INT AUTO_INCREMENT PRIMARY KEY",
    "pgsql" => "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    "sqlite" => "INTEGER PRIMARY KEY AUTOINCREMENT",
};

$db->exec("
    CREATE TABLE IF NOT EXISTS migrations (
        id {$primaryKey},
        migration VARCHAR(255) NOT NULL UNIQUE,
        batch INTEGER NOT NULL
    )
");

/*
|--------------------------------------------------------------------------
| Migration files
|--------------------------------------------------------------------------
*/

$files = glob(__DIR__ . "/migrations/*.php");

if ($files === false) {
    throw new RuntimeException("Could not read migration directory.");
}

sort($files, SORT_STRING);

$migrations = [];

foreach ($files as $file) {
    $migrations[basename($file)] = $file;
}

/*
|--------------------------------------------------------------------------
| Helpers
|--------------------------------------------------------------------------
*/

function loadMigration(string $file): array
{
    $migration = require $file;

    if (
        !is_array($migration) ||
        !isset($migration["up"], $migration["down"]) ||
        !is_callable($migration["up"]) ||
        !is_callable($migration["down"])
    ) {
        throw new RuntimeException(
            "Invalid migration: " .
                basename($file) .
                ". Expected callable 'up' and 'down'.",
        );
    }

    return $migration;
}

function completedMigrations(PDO $db): array
{
    return $db
        ->query(
            "SELECT migration, batch
         FROM migrations
         ORDER BY batch ASC, id ASC",
        )
        ->fetchAll(PDO::FETCH_ASSOC);
}

function runMigration(
    PDO $db,
    callable $operation,
    callable $recordChange,
    string $driver,
): void {
    // PostgreSQL and SQLite support transactional schema changes.
    // MySQL DDL can implicitly commit, so transactions cannot
    // guarantee atomic migrations there.
    $transactional = in_array($driver, ["pgsql", "sqlite"], true);

    if ($transactional) {
        $db->beginTransaction();
    }

    try {
        $operation($db);
        $recordChange();

        if ($transactional) {
            $db->commit();
        }
    } catch (Throwable $e) {
        if ($db->inTransaction()) {
            $db->rollBack();
        }

        throw $e;
    }
}

/*
|--------------------------------------------------------------------------
| Locking
|--------------------------------------------------------------------------
|
| Prevent two migration commands from running simultaneously
| on the same deployment.
|
| For deployments using multiple servers, a shared database-level
| lock would be required instead.
*/

$lockFile = __DIR__ . "/.migrate.lock";
$lock = fopen($lockFile, "c");

if ($lock === false || !flock($lock, LOCK_EX | LOCK_NB)) {
    exit("Another migration process is running, or the lock is unavailable.\n");
}

try {
    $completed = completedMigrations($db);

    $completedNames = array_column($completed, "migration");

    /*
    |--------------------------------------------------------------------------
    | Status
    |--------------------------------------------------------------------------
    */

    if ($command === "status") {
        foreach ($migrations as $name => $file) {
            $status = in_array($name, $completedNames, true)
                ? "Completed"
                : "Pending";

            echo "{$status}: {$name}\n";
        }

        foreach ($completedNames as $name) {
            if (!isset($migrations[$name])) {
                echo "Missing file: {$name}\n";
            }
        }

        exit(0);
    }

    /*
    |--------------------------------------------------------------------------
    | Migrate
    |--------------------------------------------------------------------------
    */

    if ($command === "migrate") {
        $batch =
            (int) $db
                ->query("SELECT COALESCE(MAX(batch), 0) FROM migrations")
                ->fetchColumn() + 1;

        $count = 0;

        foreach ($migrations as $name => $file) {
            if (in_array($name, $completedNames, true)) {
                continue;
            }

            $migration = loadMigration($file);

            runMigration(
                $db,
                $migration["up"],
                function () use ($db, $name, $batch): void {
                    $stmt = $db->prepare(
                        "INSERT INTO migrations (migration, batch)
                         VALUES (?, ?)",
                    );

                    $stmt->execute([$name, $batch]);
                },
                $driver,
            );

            echo "Migrated: {$name}\n";
            $count++;
        }

        echo $count === 0 ? "Nothing to migrate.\n" : "Migrations completed.\n";
    }

    /*
    |--------------------------------------------------------------------------
    | Rollback
    |--------------------------------------------------------------------------
    */

    if ($command === "rollback") {
        $batch = (int) $db
            ->query("SELECT COALESCE(MAX(batch), 0) FROM migrations")
            ->fetchColumn();

        if ($batch === 0) {
            echo "Nothing to rollback.\n";
        } else {
            $stmt = $db->prepare(
                "SELECT migration
                 FROM migrations
                 WHERE batch = ?
                 ORDER BY id DESC",
            );

            $stmt->execute([$batch]);

            $names = $stmt->fetchAll(PDO::FETCH_COLUMN);

            // Check all files before starting any rollback.
            foreach ($names as $name) {
                if (!isset($migrations[$name])) {
                    throw new RuntimeException(
                        "Cannot rollback: missing migration file {$name}",
                    );
                }

                loadMigration($migrations[$name]);
            }

            foreach ($names as $name) {
                $migration = loadMigration($migrations[$name]);

                runMigration(
                    $db,
                    $migration["down"],
                    function () use ($db, $name): void {
                        $stmt = $db->prepare(
                            "DELETE FROM migrations WHERE migration = ?",
                        );

                        $stmt->execute([$name]);
                    },
                    $driver,
                );

                echo "Rolled back: {$name}\n";
            }

            echo "Rollback completed.\n";
        }
    }
} catch (Throwable $e) {
    fwrite(STDERR, "Migration failed: {$e->getMessage()}\n");
    exit(1);
} finally {
    flock($lock, LOCK_UN);
    fclose($lock);
}
